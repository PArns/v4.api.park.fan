/**
 * Curated ride profiles — the link between an attraction and the glossary.
 *
 * ## What this is
 *
 * For each ride: which named track figures it contains (in ride order), what
 * kind of ride it is, who built it, and when it opened. Every id is a glossary
 * term id, so the ride page renders its layout as links into the glossary and
 * the glossary lists the rides that feature a term.
 *
 * ## Where the data comes from
 *
 * Ride layouts are **facts about a physical object**, not anybody's text. Each
 * entry was assembled from the park's own attraction page, the manufacturer's
 * project page (Mack, Intamin, Vekoma, B&M and Gerstlauer all publish element
 * lists for their installations), Wikipedia's ride articles and published
 * on-ride footage. RCDB is used the same way it already is for `rcdbId` — as a
 * link target and to confirm manufacturer/model/year — never as a text source;
 * their terms permit linking, not reuse of their content.
 *
 * Where sources disagree on an element's name (a "junior Immelmann" vs a
 * "half-loop", a "stall" vs a "zero-g stall") the entry uses the name the
 * manufacturer uses for that installation.
 *
 * ## How it is maintained
 *
 * There is no upstream feed and there will not be one — nobody publishes this
 * as data. It is written once and then edited by hand (in practice: by asking
 * Claude to research a park and extend this file). Applying it is a separate,
 * seconds-long job:
 *
 *     POST /v1/admin/apply-ride-profiles
 *
 * Rules for editing:
 * - Only add an element you can point at in footage or a published layout.
 *   An incomplete list is fine; a wrong one is worse than none.
 * - `elements` order is the ride order. Never sort it.
 * - Leave `elements` off entirely for rides with no track figures.
 * - `inversions` is what the park publishes, even when it disagrees with the
 *   element list (parks count non-inverting figures inconsistently).
 * - Slugs are validated against nothing at write time — a slug that does not
 *   match an attraction is skipped silently by the seed job, exactly like
 *   MANUAL_ATTRACTION_METADATA.
 */
